#!/usr/bin/env python3
"""Reproducible test-generation check for eliuds-eggs (R47-T042).

Background: in this track there is no per-exercise template or generator
that produces `eliuds-eggs.test.ts`. The maintained sources are:

  * `exercises/practice/eliuds-eggs/.meta/tests.toml` — synced from the
    canonical data in exercism/problem-specifications with configlet
    (`./bin/fetch-configlet`, then `./bin/configlet sync --tests
    --exercise eliuds-eggs`); it lists the canonical cases by UUID.
  * `exercises/practice/eliuds-eggs/eliuds-eggs.test.ts` — maintained by
    hand; it must implement exactly the cases tests.toml includes.

This check makes that route reproducible without inventing a template:

  1. Parses tests.toml (UUID -> description, inclusion).
  2. Parses the test file (test name -> input value, expected result),
     including cases that are disabled with xit (they still count as
     implemented cases; enabling them is the test runner's job).
  3. Asserts both sources name exactly the same cases — no case is
     silently dropped or added.
  4. Asserts every expected result equals the popcount (number of 1
     bits) of its input, which is the exercise's specification, and
     pins the three anchor cases: 0 eggs -> eggCount(0) = 0,
     1 egg -> eggCount(16) = 1, 4 eggs -> eggCount(89) = 4.
  5. "Regenerates" the canonical case table from the two sources into
     two separate temporary directories and compares the results byte
     for byte. The generated table contains no timestamp or other
     nondeterministic field, so the two generations must be identical.

Usage: python3 tools/course_checks/r47-t042.py [path-to-exercise-dir]
Exit code is non-zero when any assertion fails.
"""

import json
import re
import sys
import tempfile
import tomllib
from pathlib import Path

ANCHORS = {
    "0 eggs": (0, 0),
    "1 egg": (16, 1),
    "4 eggs": (89, 4),
}

TEST_RE = re.compile(
    r"(?:x?it)\('([^']+)',\s*\(\)\s*=>\s*\{\s*"
    r"const expected = (\d+)\s*"
    r"const actual = eggCount\((\d+)\)",
    re.S,
)


def load_cases(exercise: Path):
    with open(exercise / ".meta" / "tests.toml", "rb") as fh:
        toml = tomllib.load(fh)
    toml_cases = []
    for uuid, entry in toml.items():
        if entry.get("include") is False:
            continue
        toml_cases.append({"uuid": uuid, "description": entry["description"]})

    test_src = (exercise / "eliuds-eggs.test.ts").read_text()
    test_cases = {}
    for name, expected, value in TEST_RE.findall(test_src):
        test_cases[name] = {"input": int(value), "expected": int(expected)}
    return toml_cases, test_cases


def generate_table(toml_cases, test_cases) -> str:
    """Render the canonical case table deterministically (no timestamps)."""
    lines = [
        "# eliuds-eggs canonical cases (generated by tools/course_checks/r47-t042.py)",
        "",
        "| UUID | Description | Input | Expected |",
        "| --- | --- | --- | --- |",
    ]
    for case in toml_cases:
        impl = test_cases[case["description"]]
        lines.append(
            f"| {case['uuid']} | {case['description']} | "
            f"{impl['input']} | {impl['expected']} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    if len(sys.argv) > 1:
        exercise = Path(sys.argv[1])
    else:
        exercise = (
            Path(__file__).resolve().parents[2]
            / "exercises/practice/eliuds-eggs"
        )

    failures = []
    toml_cases, test_cases = load_cases(exercise)

    toml_names = [c["description"] for c in toml_cases]
    if sorted(toml_names) != sorted(test_cases):
        failures.append(
            f"case mismatch: tests.toml has {sorted(toml_names)}, "
            f"test file has {sorted(test_cases)}"
        )

    for case in toml_cases:
        name = case["description"]
        impl = test_cases.get(name)
        if impl is None:
            continue
        popcount = bin(impl["input"]).count("1")
        if impl["expected"] != popcount:
            failures.append(
                f"{name}: expected {impl['expected']} != popcount({impl['input']}) = {popcount}"
            )

    for name, (value, expected) in ANCHORS.items():
        impl = test_cases.get(name)
        if impl is None:
            failures.append(f"anchor case missing from test file: {name}")
        elif (impl["input"], impl["expected"]) != (value, expected):
            failures.append(
                f"anchor {name}: found eggCount({impl['input']}) = {impl['expected']}, "
                f"expected eggCount({value}) = {expected}"
            )

    table = generate_table(toml_cases, test_cases)
    with tempfile.TemporaryDirectory() as d1, tempfile.TemporaryDirectory() as d2:
        p1 = Path(d1) / "cases.md"
        p2 = Path(d2) / "cases.md"
        p1.write_text(table)
        p2.write_text(generate_table(*load_cases(exercise)))
        if p1.read_bytes() != p2.read_bytes():
            failures.append("two generations of the case table differ")

    report = {
        "exercise": str(exercise),
        "cases_in_tests_toml": len(toml_cases),
        "cases_in_test_file": len(test_cases),
        "anchors": {k: {"input": v[0], "expected": v[1]} for k, v in ANCHORS.items()},
        "regeneration_deterministic": not any(
            "generations" in f for f in failures
        ),
        "failures": failures,
        "result": "PASS" if not failures else "FAIL",
    }
    print(json.dumps(report, indent=2))
    print("\n" + table)
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
